import { AsyncLocalStorage } from 'node:async_hooks';
import dotenv from 'dotenv';
dotenv.config();

const txStore = new AsyncLocalStorage();
const TEST_SQLITE = process.env.TEST_SQLITE === '1';
let pool;
let sqliteDb;
const connectionString = process.env.DATABASE_URL || process.env.POSTGRES_URL || process.env.POSTGRES_URL_NON_POOLING || process.env.POSTGRES_PRISMA_URL || '';

function replacePlaceholders(sql, params) {
  let index = 0;
  const converted = String(sql).replace(/\?/g, () => `$${++index}`);
  if (index !== params.length) throw new Error(`SQL placeholder mismatch: expected ${index}, received ${params.length}`);
  return converted;
}

if (TEST_SQLITE) {
  const { DatabaseSync } = await import('node:sqlite');
  const { fileURLToPath } = await import('node:url');
  const { dirname, resolve } = await import('node:path');
  const __dirname = dirname(fileURLToPath(import.meta.url));
  sqliteDb = new DatabaseSync(resolve(process.env.TEST_SQLITE_PATH || resolve(__dirname, '../data/securedocs_v2.db')));
  sqliteDb.exec('PRAGMA foreign_keys = ON');
  pool = {
    async query(sql, params = []) {
      const q = String(sql).replace(/\$\d+/g, '?');
      const stmt = sqliteDb.prepare(q);
      if (/^(SELECT|WITH|PRAGMA)\b/i.test(q.trim())) return { rows: stmt.all(...params), rowCount: 0 };
      const info = stmt.run(...params);
      return { rows: [], rowCount: Number(info.changes ?? 0) };
    },
    async connect() { return { query: async (...args) => { if (args[0] === 'BEGIN') sqliteDb.prepare('BEGIN').run(); else if (args[0] === 'COMMIT') sqliteDb.prepare('COMMIT').run(); else if (args[0] === 'ROLLBACK') sqliteDb.prepare('ROLLBACK').run(); else return pool.query(...args); }, release() {} }; },
    async end() { sqliteDb.close(); },
  };
} else {
  if (!connectionString && (process.env.NODE_ENV === 'production' || process.env.VERCEL)) throw new Error('DATABASE_URL (or a supported POSTGRES_* URL) is required in production.');
  if (connectionString) {
    const { default: pg } = await import('pg');
    const { Pool } = pg;
    pool = new Pool({
      connectionString,
      max: Number(process.env.PG_POOL_MAX || 5),
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
      ssl: process.env.PGSSL === 'false' ? false : undefined,
    });
    pool.on('error', err => console.error('PostgreSQL pool error:', err));
  }
}

function executor() {
  return txStore.getStore() || pool;
}

async function query(sql, params = []) {
  const client = executor();
  if (!client) throw new Error('Database is not configured. Set DATABASE_URL.');
  return client.query(replacePlaceholders(sql, params), params);
}

export const db = {
  prepare(sql) {
    return {
      async get(...params) {
        const result = await query(sql, params);
        return result.rows[0];
      },
      async all(...params) {
        const result = await query(sql, params);
        return result.rows;
      },
      async run(...params) {
        let runSql = String(sql).trim().replace(/;\s*$/, '');
        const isInsert = /^INSERT\s/i.test(runSql) && !/\bRETURNING\b/i.test(runSql);
        if (isInsert) runSql += ' RETURNING id';
        if (TEST_SQLITE) {
          const q = runSql.replace(/\$\d+/g, '?');
          const info = sqliteDb.prepare(q.replace(/\s+RETURNING\s+id\s*$/i, '')).run(...params);
          return { changes: Number(info.changes ?? 0), lastInsertRowid: Number(info.lastInsertRowid ?? 0) };
        }
        const result = await query(runSql, params);
        return { changes: result.rowCount, lastInsertRowid: result.rows[0]?.id ?? null };
      },
    };
  },
  async exec(sql) {
    return query(sql, []);
  },
  async transaction(fn) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await txStore.run(client, fn);
      await client.query('COMMIT');
      return result;
    } catch (err) {
      await client.query('ROLLBACK');
      throw err;
    } finally {
      client.release();
    }
  },
  async close() {
    await pool.end();
  },
};

